export const categoryIcon = (category: string): string => '/food-icons/' + (BY_CATEGORY[category] ?? 'rice_bowl') + '.svg';

export function foodIcon(name: string, category = ''): string {
  const hit = BY_KEYWORD.find(([re]) => re.test(name));
  return hit ? '/food-icons/' + hit[1] + '.svg' : categoryIcon(category);
}
